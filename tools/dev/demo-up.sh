#!/usr/bin/env bash
# One-command local demo: MySQL/Redis -> backend -> UI -> seed -> URL.
#
#   tools/dev/demo-up.sh
#
# It creates a random .env only when .env is missing, never prints the secret
# values, and falls back to tools/dev/web_static_proxy.py when the nginx image
# is unavailable. The default is to seed 12 synthetic jobs; --no-seed opts out.
#
# Useful overrides for tests or an existing stack:
#   DEMO_PROJECT, DEMO_ENV_FILE, DEMO_API_PORT, DEMO_WEB_PORT,
#   DEMO_MYSQL_PORT, DEMO_REDIS_PORT, DEMO_BACKEND_IMAGE,
#   DEMO_BUILD_BACKEND=0, DEMO_INTERNAL_TOKEN
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

PROJECT="${DEMO_PROJECT:-jobpilot-demo}"
ENV_FILE="${DEMO_ENV_FILE:-$ROOT/.env}"
API_PORT="${DEMO_API_PORT:-8080}"
WEB_PORT="${DEMO_WEB_PORT:-8081}"
MYSQL_PORT="${DEMO_MYSQL_PORT:-3306}"
REDIS_PORT="${DEMO_REDIS_PORT:-6379}"
SEED=1

while [ "$#" -gt 0 ]; do
    case "$1" in
        --no-seed) SEED=0; shift ;;
        --no-build) DEMO_BUILD_BACKEND=0; shift ;;
        -h|--help)
            sed -n '2,18p' "$0"
            exit 0
            ;;
        *)
            echo "demo-up: unknown argument: $1" >&2
            exit 2
            ;;
    esac
done

say() { printf '\n=== %s ===\n' "$1"; }
fail() { echo "demo-up: $*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || fail "Docker is not on PATH"
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is not available"
command -v curl >/dev/null 2>&1 || fail "curl is not on PATH"
command -v python3 >/dev/null 2>&1 || fail "python3 is not on PATH"

gen_secret() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 24
    else
        python3 -c 'import secrets; print(secrets.token_hex(24))'
    fi
}

if [ ! -f "$ENV_FILE" ]; then
    say "create $ENV_FILE"
    mkdir -p "$(dirname "$ENV_FILE")"
    umask 077
    cat > "$ENV_FILE" <<EOF
# Generated by tools/dev/demo-up.sh. Do not commit this file.
MYSQL_ROOT_PASSWORD=$(gen_secret)
MYSQL_DATABASE=jobpilot
MYSQL_USER=jobpilot
MYSQL_PASSWORD=$(gen_secret)
JOBPILOT_BACKEND_HOST_PORT=$API_PORT
JOBPILOT_WEB_HOST_PORT=$WEB_PORT
INTERNAL_API_TOKEN=$(gen_secret)
EOF
    chmod 600 "$ENV_FILE"
    echo "created $ENV_FILE (secret values are not printed)"
else
    echo "using existing $ENV_FILE (not modified)"
fi

set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a

[ -n "${MYSQL_ROOT_PASSWORD:-}" ] || fail "MYSQL_ROOT_PASSWORD is empty in $ENV_FILE"
[ -n "${MYSQL_PASSWORD:-}" ] || fail "MYSQL_PASSWORD is empty in $ENV_FILE"

TOKEN="${DEMO_INTERNAL_TOKEN:-${INTERNAL_API_TOKEN:-}}"
if [ -z "$TOKEN" ]; then
    TOKEN="$(gen_secret)"
    echo "INTERNAL_API_TOKEN is empty in $ENV_FILE; using an ephemeral token for this run"
fi

IMAGE="${DEMO_BACKEND_IMAGE:-${JOBPILOT_BACKEND_IMAGE:-jobpilot-backend:demo}}"
WEB_IMAGE="${DEMO_WEB_IMAGE:-${JOBPILOT_WEB_IMAGE:-nginx:1.27-alpine}}"
BUILD_BACKEND="${DEMO_BUILD_BACKEND:-1}"

compose() {
    JOBPILOT_MYSQL_CONTAINER_NAME="${PROJECT}-mysql" \
    JOBPILOT_REDIS_CONTAINER_NAME="${PROJECT}-redis" \
    JOBPILOT_BACKEND_CONTAINER_NAME="${PROJECT}-backend" \
    JOBPILOT_WEB_CONTAINER_NAME="${PROJECT}-web" \
    JOBPILOT_MYSQL_HOST_PORT="$MYSQL_PORT" \
    JOBPILOT_REDIS_HOST_PORT="$REDIS_PORT" \
    JOBPILOT_BACKEND_HOST_PORT="$API_PORT" \
    JOBPILOT_WEB_HOST_PORT="$WEB_PORT" \
    JOBPILOT_BACKEND_IMAGE="$IMAGE" \
    JOBPILOT_WEB_IMAGE="$WEB_IMAGE" \
    INTERNAL_API_TOKEN="$TOKEN" \
    docker compose --env-file "$ENV_FILE" -p "$PROJECT" "$@"
}

API="http://127.0.0.1:${API_PORT}"
WEB="http://127.0.0.1:${WEB_PORT}"
mkdir -p "$ROOT/build"

say "start MySQL and Redis"
compose up -d mysql redis

if [ "$BUILD_BACKEND" = "1" ]; then
    say "build backend image"
    compose --profile app build backend
else
    say "skip backend build (DEMO_BUILD_BACKEND=0)"
    docker image inspect "$IMAGE" >/dev/null 2>&1 || fail "backend image $IMAGE is not available"
fi

say "start backend"
compose --profile app up -d
for _ in $(seq 1 60); do
    if curl -fsS --max-time 2 "$API/health" >/dev/null 2>&1; then
        break
    fi
    sleep 1
done
curl -fsS --max-time 2 "$API/health" >/dev/null || {
    compose logs --tail=60 backend || true
    fail "backend did not become healthy at $API/health"
}
echo "backend health: $API/health"

say "start Web UI"
WEB_MODE="nginx"
if ! compose --profile app --profile web up -d > "$ROOT/build/demo-web-up.log" 2>&1; then
    WEB_MODE="python-proxy"
    echo "nginx web profile unavailable; falling back to web_static_proxy.py"
fi
if [ "$WEB_MODE" = "nginx" ]; then
    for _ in $(seq 1 20); do
        if curl -fsS --max-time 2 "$WEB/" >/dev/null 2>&1; then
            break
        fi
        sleep 0.5
    done
    if ! curl -fsS --max-time 2 "$WEB/" >/dev/null 2>&1; then
        WEB_MODE="python-proxy"
        compose --profile web stop web >/dev/null 2>&1 || true
        echo "nginx web service did not become reachable; falling back to web_static_proxy.py"
    fi
fi

if [ "$WEB_MODE" = "python-proxy" ]; then
    # A failed compose up can still leave a created web container behind; stop
    # it so the Python fallback can bind the same host port.
    compose --profile web stop web >/dev/null 2>&1 || true
    if [ -f "$ROOT/build/demo-web-proxy.pid" ]; then
        old_pid="$(cat "$ROOT/build/demo-web-proxy.pid" 2>/dev/null || true)"
        [ -n "$old_pid" ] && kill "$old_pid" >/dev/null 2>&1 || true
    fi
    nohup python3 "$ROOT/tools/dev/web_static_proxy.py" \
        --root "$ROOT/web" --port "$WEB_PORT" --backend "$API" \
        > "$ROOT/build/demo-web-proxy.log" 2>&1 &
    echo $! > "$ROOT/build/demo-web-proxy.pid"
    for _ in $(seq 1 30); do
        if curl -fsS --max-time 2 "$WEB/" >/dev/null 2>&1; then
            break
        fi
        sleep 0.5
    done
    curl -fsS --max-time 2 "$WEB/" >/dev/null || {
        cat "$ROOT/build/demo-web-proxy.log" >&2 || true
        fail "web fallback did not become reachable at $WEB"
    }
fi

if [ "$SEED" = "1" ]; then
    say "seed demo jobs"
    DEMO_ENV_FILE="$ENV_FILE" DEMO_API_PORT="$API_PORT" \
    DEMO_INTERNAL_TOKEN="$TOKEN" \
        "$ROOT/tools/dev/demo-seed.sh"
fi

say "ready"
echo "DEMO_READY url=$WEB"
echo "env=$ENV_FILE project=$PROJECT backend=$API"
if [ "$WEB_MODE" = "python-proxy" ]; then
    echo "web_proxy_pid=$(cat "$ROOT/build/demo-web-proxy.pid")"
    echo "web_proxy_log=$ROOT/build/demo-web-proxy.log"
fi
echo "stop: docker compose --env-file $ENV_FILE -p $PROJECT --profile app --profile web down"
